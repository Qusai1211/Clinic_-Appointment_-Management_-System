-- 1. جدول التخصصات
CREATE TABLE Specialties (
    SpecialtyId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SpecialtyName VARCHAR2(100) NOT NULL,
    Description VARCHAR2(500)
);
-- 2. جدول الأطباء
CREATE TABLE Doctors (
    DoctorId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FullName VARCHAR2(150) NOT NULL,
    Qualifications VARCHAR2(250),
    ConsultationFee NUMBER(10, 2),
    ProfileImageUrl VARCHAR2(500),
    IsFeatured NUMBER(1) DEFAULT 0,
    SpecialtyId NUMBER,
    CONSTRAINT fk_doctor_specialty FOREIGN KEY (SpecialtyId) 
        REFERENCES Specialties(SpecialtyId) ON DELETE SET NULL
);

-- 3. جدول أوقات دوام الأطباء
CREATE TABLE DoctorWorkingHours (
    WorkingHoursId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DayOfWeek VARCHAR2(20) NOT NULL,
    StartTime VARCHAR2(10) NOT NULL,
    EndTime VARCHAR2(10) NOT NULL,
    DoctorId NUMBER,
    CONSTRAINT fk_workhours_doctor FOREIGN KEY (DoctorId) 
        REFERENCES Doctors(DoctorId) ON DELETE CASCADE
);

-- 4. جدول الفترات المتاحة للحجز
CREATE TABLE AppointmentSlots (
    SlotId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SlotDate DATE NOT NULL,
    SlotTime VARCHAR2(10) NOT NULL,
    IsAvailable NUMBER(1) DEFAULT 1,
    DoctorId NUMBER,
    CONSTRAINT fk_slot_doctor FOREIGN KEY (DoctorId) 
        REFERENCES Doctors(DoctorId) ON DELETE CASCADE
);

-- 5. جدول المرضى
CREATE TABLE Patients (
    PatientId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FullName VARCHAR2(150) NOT NULL,
    PhoneNumber VARCHAR2(20) NOT NULL,
    Email VARCHAR2(150) NOT NULL,
    DateOfBirth DATE NOT NULL
);

-- 6. جدول المواعيد
CREATE TABLE Appointments (
    AppointmentId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ReferenceNumber VARCHAR2(50) UNIQUE,
    AppointmentDate DATE NOT NULL,
    AppointmentTime VARCHAR2(10) NOT NULL,
    Status VARCHAR2(30) DEFAULT 'Pending',
    DoctorId NUMBER,
    SlotId NUMBER,
    PatientId NUMBER,
    CONSTRAINT fk_appointment_doctor FOREIGN KEY (DoctorId) 
        REFERENCES Doctors(DoctorId) ON DELETE SET NULL,
    CONSTRAINT fk_appointment_slot FOREIGN KEY (SlotId) 
        REFERENCES AppointmentSlots(SlotId) ON DELETE CASCADE,
    CONSTRAINT fk_appointment_patient FOREIGN KEY (PatientId) 
        REFERENCES Patients(PatientId) ON DELETE CASCADE
);

-- 7. جدول المشرفين
CREATE TABLE Admins (
    AdminId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AdminName VARCHAR2(100) NOT NULL,
    PasswordHash VARCHAR2(255) NOT NULL
);
