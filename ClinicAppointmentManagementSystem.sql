-- 2. تطبيق الـ Package Body (العمليات البرمجية)
CREATE OR REPLACE PACKAGE BODY PKG_CLINIC_OPERATIONS AS

    PROCEDURE REGISTER_PATIENT(
        p_FullName    IN  VARCHAR2,
        p_PhoneNumber IN  VARCHAR2,
        p_Email       IN  VARCHAR2,
        p_DateOfBirth IN  DATE,
        o_PatientId   OUT NUMBER
    ) IS
    BEGIN
        SELECT PatientId INTO o_PatientId
        FROM Patients
        WHERE Email = p_Email OR PhoneNumber = p_PhoneNumber;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            INSERT INTO Patients (FullName, PhoneNumber, Email, DateOfBirth)
            VALUES (p_FullName, p_PhoneNumber, p_Email, p_DateOfBirth)
            RETURNING PatientId INTO o_PatientId;
            COMMIT;
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20001, 'خطأ أثناء تسجيل المريض: ' || SQLERRM);
    END REGISTER_PATIENT;

    PROCEDURE BOOK_APPOINTMENT(
        p_DoctorId        IN  NUMBER,
        p_PatientId       IN  NUMBER,
        p_SlotId          IN  NUMBER,
        p_AppointmentDate IN  DATE,
        p_AppointmentTime IN  VARCHAR2,
        o_AppointmentId   OUT NUMBER,
        o_ReferenceNumber OUT VARCHAR2
    ) IS
        v_IsAvailable NUMBER;
    BEGIN
        SELECT IsAvailable INTO v_IsAvailable 
        FROM AppointmentSlots 
        WHERE SlotId = p_SlotId;

        IF v_IsAvailable = 1 THEN
            -- توليد رقم مرجعي تلقائي
            o_ReferenceNumber := 'REF-' || TO_CHAR(SYSDATE, 'YYYYMMDD') || '-' || LPAD(TRUNC(DBMS_RANDOM.VALUE(1000, 9999)), 4, '0');

            INSERT INTO Appointments (ReferenceNumber, AppointmentDate, AppointmentTime, Status, DoctorId, SlotId, PatientId)
            VALUES (o_ReferenceNumber, TRUNC(p_AppointmentDate), p_AppointmentTime, 'Scheduled', p_DoctorId, p_SlotId, p_PatientId)
            RETURNING AppointmentId INTO o_AppointmentId;

            UPDATE AppointmentSlots 
            SET IsAvailable = 0 
            WHERE SlotId = p_SlotId;

            COMMIT;
        ELSE
            RAISE_APPLICATION_ERROR(-20002, 'عذراً، هذا الموعد غير متاح أو تم حجزه مسبقاً.');
        END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20003, 'رقم الفترة الزمنية غير موجود.');
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20004, 'حدث خطأ غير متوقع أثناء حجز الموعد: ' || SQLERRM);
    END BOOK_APPOINTMENT;

    PROCEDURE CANCEL_APPOINTMENT(
        p_AppointmentId IN NUMBER
    ) IS
        v_SlotId NUMBER;
    BEGIN
        UPDATE Appointments 
        SET Status = 'Cancelled'
        WHERE AppointmentId = p_AppointmentId
        RETURNING SlotId INTO v_SlotId;

        IF v_SlotId IS NOT NULL THEN
            UPDATE AppointmentSlots 
            SET IsAvailable = 1 
            WHERE SlotId = v_SlotId;
        END IF;

        COMMIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20005, 'الموعد غير موجود.');
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20006, 'حدث خطأ أثناء إلغاء الموعد: ' || SQLERRM);
    END CANCEL_APPOINTMENT;

    PROCEDURE UPDATE_APPOINTMENT_STATUS(
        p_AppointmentId IN NUMBER,
        p_Status        IN VARCHAR2
    ) IS
    BEGIN
        UPDATE Appointments
        SET Status = p_Status
        WHERE AppointmentId = p_AppointmentId;
        
        COMMIT;
    END UPDATE_APPOINTMENT_STATUS;

END PKG_CLINIC_OPERATIONS;
/

