-- ----------------------------------------------------------------------------
-- Stored Procedures Package Body
-- ----------------------------------------------------------------------------
CREATE OR REPLACE PACKAGE BODY PKG_CLINIC_OPERATIONS AS

    PROCEDURE REGISTER_PATIENT(
        p_FullName    IN  VARCHAR2,
        p_PhoneNumber IN  VARCHAR2,
        p_Email       IN  VARCHAR2,
        p_DateOfBirth IN  DATE,
        o_PatientId   OUT NUMBER
    ) IS
    BEGIN
        BEGIN
            SELECT PatientId INTO o_PatientId
            FROM (
                SELECT PatientId 
                FROM Patients
                WHERE LOWER(Email) = LOWER(p_Email) OR PhoneNumber = p_PhoneNumber
                ORDER BY PatientId ASC
            )
            WHERE ROWNUM = 1;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                INSERT INTO Patients (FullName, PhoneNumber, Email, DateOfBirth)
                VALUES (p_FullName, p_PhoneNumber, LOWER(p_Email), TRUNC(p_DateOfBirth))
                RETURNING PatientId INTO o_PatientId;
                COMMIT;
        END;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20001, 'Error registering patient: ' || SQLERRM);
    END REGISTER_PATIENT;

    PROCEDURE BOOK_APPOINTMENT(
        p_DoctorId        IN  NUMBER,
        p_PatientId       IN  NUMBER,
        p_SlotId          IN  NUMBER,
        p_AppointmentDate IN  DATE,
        p_AppointmentTime IN  VARCHAR2,
        o_AppointmentId   OUT NUMBER,
        o_ReferenceNumber OUT VARCHAR2
    ) IS
        v_IsAvailable NUMBER;
        v_SlotDoctorId NUMBER;
    BEGIN
        -- Concurrency lock: lock the slot row FOR UPDATE to prevent race conditions
        SELECT IsAvailable, DoctorId INTO v_IsAvailable, v_SlotDoctorId
        FROM AppointmentSlots 
        WHERE SlotId = p_SlotId
        FOR UPDATE;

        IF v_SlotDoctorId != p_DoctorId THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20007, 'Selected slot does not match the requested doctor.');
        END IF;

        IF v_IsAvailable = 1 THEN
            -- Generate unique human-readable reference number
            o_ReferenceNumber := 'REF-' || TO_CHAR(SYSDATE, 'YYYYMMDD') || '-' || LPAD(TRUNC(DBMS_RANDOM.VALUE(1000, 9999)), 4, '0');

            INSERT INTO Appointments (
                ReferenceNumber, AppointmentDate, AppointmentTime, 
                Status, DoctorId, SlotId, PatientId
            )
            VALUES (
                o_ReferenceNumber, TRUNC(p_AppointmentDate), p_AppointmentTime, 
                'Scheduled', p_DoctorId, p_SlotId, p_PatientId
            )
            RETURNING AppointmentId INTO o_AppointmentId;

            UPDATE AppointmentSlots 
            SET IsAvailable = 0 
            WHERE SlotId = p_SlotId;

            COMMIT;
        ELSE
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20002, 'The selected appointment slot is no longer available.');
        END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20003, 'Appointment slot not found.');
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20004, 'Booking failed: ' || SQLERRM);
    END BOOK_APPOINTMENT;

    PROCEDURE CANCEL_APPOINTMENT(
        p_AppointmentId IN NUMBER
    ) IS
        v_SlotId NUMBER;
        v_Status VARCHAR2(30);
    BEGIN
        SELECT SlotId, Status INTO v_SlotId, v_Status
        FROM Appointments
        WHERE AppointmentId = p_AppointmentId
        FOR UPDATE;

        IF v_Status = 'Cancelled' THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20008, 'Appointment is already cancelled.');
        END IF;

        UPDATE Appointments 
        SET Status = 'Cancelled'
        WHERE AppointmentId = p_AppointmentId;

        IF v_SlotId IS NOT NULL THEN
            UPDATE AppointmentSlots 
            SET IsAvailable = 1 
            WHERE SlotId = v_SlotId;
        END IF;

        COMMIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20005, 'Appointment record not found.');
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20006, 'Error cancelling appointment: ' || SQLERRM);
    END CANCEL_APPOINTMENT;

    PROCEDURE UPDATE_APPOINTMENT_STATUS(
        p_AppointmentId IN NUMBER,
        p_Status        IN VARCHAR2
    ) IS
        v_SlotId NUMBER;
    BEGIN
        UPDATE Appointments
        SET Status = p_Status
        WHERE AppointmentId = p_AppointmentId
        RETURNING SlotId INTO v_SlotId;

        -- If updated to Cancelled, reopen the slot
        IF p_Status = 'Cancelled' AND v_SlotId IS NOT NULL THEN
            UPDATE AppointmentSlots
            SET IsAvailable = 1
            WHERE SlotId = v_SlotId;
        END IF;
        
        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20009, 'Failed to update appointment status: ' || SQLERRM);
    END UPDATE_APPOINTMENT_STATUS;

END PKG_CLINIC_OPERATIONS;
