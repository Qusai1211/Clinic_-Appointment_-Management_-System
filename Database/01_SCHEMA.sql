SET DEFINE OFF;

-- ----------------------------------------------------------------------------
-- 0. Safely clean existing clinic tables and sequences in this schema
-- ----------------------------------------------------------------------------
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'APPOINTMENTS', 'APPOINTMENTSLOTS', 'DOCTORWORKINGHOURS', 
        'DOCTORS', 'SPECIALTIES', 'PATIENTS', 'ADMINS', 'ROLES'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;

    FOR s IN (SELECT sequence_name FROM user_sequences WHERE sequence_name IN ('SEQ_APPT_REF')) LOOP
        EXECUTE IMMEDIATE 'DROP SEQUENCE ' || s.sequence_name;
    END LOOP;
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

-- ----------------------------------------------------------------------------
-- 1. Sequence: Appointment Reference Number Generator
-- ----------------------------------------------------------------------------
CREATE SEQUENCE SEQ_APPT_REF 
    MINVALUE 1000 
    MAXVALUE 999999999999 
    INCREMENT BY 1 
    START WITH 1250 
    NOCACHE 
    NOORDER 
    NOCYCLE;

-- ----------------------------------------------------------------------------
-- 2. Table: Roles (Admin, Receptionist, Staff)
-- ----------------------------------------------------------------------------
CREATE TABLE Roles (
    RoleId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RoleName VARCHAR2(50) NOT NULL,
    Description VARCHAR2(250),
    CONSTRAINT UQ_ROLES_NAME UNIQUE (RoleName)
);

-- ----------------------------------------------------------------------------
-- 3. Table: Admins (Administrator credentials & authorization)
--    Preserves newest improvements from feature/admin-email
-- ----------------------------------------------------------------------------
CREATE TABLE Admins (
    AdminId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AdminName VARCHAR2(100) NOT NULL,
    PasswordHash VARCHAR2(255) NOT NULL,
    RoleId NUMBER DEFAULT 1,
    IsActive NUMBER(1,0) DEFAULT 1,
    Email VARCHAR2(150),
    CONSTRAINT UQ_ADMIN_NAME UNIQUE (AdminName),
    CONSTRAINT UQ_ADMINS_EMAIL UNIQUE (Email),
    CONSTRAINT CK_ADMIN_ACTIVE CHECK (IsActive IN (0, 1)),
    CONSTRAINT FK_ADMIN_ROLE FOREIGN KEY (RoleId) REFERENCES Roles(RoleId) ON DELETE SET NULL
);

-- ----------------------------------------------------------------------------
-- 4. Table: Specialties (Medical specialties)
-- ----------------------------------------------------------------------------
CREATE TABLE Specialties (
    SpecialtyId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SpecialtyName VARCHAR2(100) NOT NULL,
    Description VARCHAR2(500),
    CONSTRAINT UQ_SPECIALTY_NAME UNIQUE (SpecialtyName)
);

-- ----------------------------------------------------------------------------
-- 5. Table: Doctors (Clinic medical staff)
-- ----------------------------------------------------------------------------
CREATE TABLE Doctors (
    DoctorId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FullName VARCHAR2(150) NOT NULL,
    Qualifications VARCHAR2(250),
    ConsultationFee NUMBER(10, 2) DEFAULT 0.00,
    ProfileImageUrl VARCHAR2(500),
    IsFeatured NUMBER(1,0) DEFAULT 0,
    SpecialtyId NUMBER,
    IsActive NUMBER(1,0) DEFAULT 1,
    CONSTRAINT CK_DOC_ACTIVE CHECK (IsActive IN (0, 1)),
    CONSTRAINT CK_DOC_FEE_POS CHECK (ConsultationFee >= 0),
    CONSTRAINT FK_DOCTOR_SPECIALTY FOREIGN KEY (SpecialtyId) 
        REFERENCES Specialties(SpecialtyId) ON DELETE SET NULL
);

-- ----------------------------------------------------------------------------
-- 6. Table: DoctorWorkingHours (Weekly schedule per doctor)
-- ----------------------------------------------------------------------------
CREATE TABLE DoctorWorkingHours (
    WorkingHoursId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DayOfWeek VARCHAR2(50) NOT NULL,
    StartTime VARCHAR2(10) NOT NULL,
    EndTime VARCHAR2(10) NOT NULL,
    DoctorId NUMBER,
    CONSTRAINT FK_WORKHOURS_DOCTOR FOREIGN KEY (DoctorId) 
        REFERENCES Doctors(DoctorId) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 7. Table: AppointmentSlots (Individual bookable slots)
-- ----------------------------------------------------------------------------
CREATE TABLE AppointmentSlots (
    SlotId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SlotDate DATE NOT NULL,
    SlotTime VARCHAR2(10) NOT NULL,
    IsAvailable NUMBER(1,0) DEFAULT 1,
    DoctorId NUMBER,
    CONSTRAINT CK_SLOT_AVAILABLE CHECK (IsAvailable IN (0, 1)),
    CONSTRAINT FK_SLOT_DOCTOR FOREIGN KEY (DoctorId) 
        REFERENCES Doctors(DoctorId) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 8. Table: Patients (Registered clinic patients)
-- ----------------------------------------------------------------------------
CREATE TABLE Patients (
    PatientId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FullName VARCHAR2(150) NOT NULL,
    PhoneNumber VARCHAR2(20) NOT NULL,
    Email VARCHAR2(150) NOT NULL,
    DateOfBirth DATE NOT NULL,
    IsActive NUMBER(1,0) DEFAULT 1,
    CONSTRAINT CK_PAT_ACTIVE CHECK (IsActive IN (0, 1)),
    CONSTRAINT UQ_PATIENT_EMAIL UNIQUE (Email)
);

-- ----------------------------------------------------------------------------
-- 9. Table: Appointments (Booked clinical appointments)
-- ----------------------------------------------------------------------------
CREATE TABLE Appointments (
    AppointmentId NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ReferenceNumber VARCHAR2(50) NOT NULL,
    AppointmentDate DATE NOT NULL,
    AppointmentTime VARCHAR2(10) NOT NULL,
    Status VARCHAR2(30) DEFAULT 'Scheduled',
    DoctorId NUMBER,
    SlotId NUMBER,
    PatientId NUMBER,
    CONSTRAINT UQ_APPOINTMENT_REF UNIQUE (ReferenceNumber),
    CONSTRAINT CK_APPT_STATUS CHECK (Status IN ('Scheduled', 'Confirmed', 'Completed', 'Cancelled')),
    CONSTRAINT FK_APPT_DOCTOR FOREIGN KEY (DoctorId) 
        REFERENCES Doctors(DoctorId) ON DELETE CASCADE,
    CONSTRAINT FK_APPT_SLOT FOREIGN KEY (SlotId) 
        REFERENCES AppointmentSlots(SlotId) ON DELETE SET NULL,
    CONSTRAINT FK_APPT_PATIENT FOREIGN KEY (PatientId) 
        REFERENCES Patients(PatientId) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 10. Performance Indexes
-- ----------------------------------------------------------------------------
CREATE INDEX IX_DOCTORS_SPECIALTY ON Doctors(SpecialtyId);
CREATE INDEX IX_SLOTS_DOCTOR_DATE ON AppointmentSlots(DoctorId, SlotDate, IsAvailable);
CREATE INDEX IX_APPT_DOCTOR ON Appointments(DoctorId);
CREATE INDEX IX_APPT_PATIENT ON Appointments(PatientId);
CREATE INDEX IX_APPT_DATE_STATUS ON Appointments(AppointmentDate, Status);
